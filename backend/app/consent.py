"""
consent.py – Driver consent gate for VERD.

Safety invariant: No outbound call (TinyFish station search, ticket creation,
or any other external action) may proceed unless the driver has explicitly
granted consent for the current session.

Rules enforced here:
- Consent is per-session (in-memory, not persisted – no PII stored).
- Denied consent permanently blocks outbound calls for that session.
- Pending consent (None) also blocks outbound calls.
- Only a fresh Approve tap from the driver can grant consent.
- Outbound calls check can_call_outbound() before any external request.
"""

from __future__ import annotations

import time
from enum import Enum

from pydantic import BaseModel


# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------

class ConsentStatus(str, Enum):
    PENDING = "pending"    # Driver has not yet responded
    GRANTED = "granted"   # Driver tapped Approve
    DENIED = "denied"     # Driver tapped Deny


class ConsentState(BaseModel):
    """Current consent state for one session."""

    session_id: str
    status: ConsentStatus = ConsentStatus.PENDING
    timestamp: float | None = None   # When the driver responded

    @property
    def can_call_outbound(self) -> bool:
        """True only when driver has explicitly granted consent."""
        return self.status == ConsentStatus.GRANTED


class ConsentRequest(BaseModel):
    """Request body for POST /consent."""

    session_id: str
    granted: bool   # True = Approve, False = Deny


class ConsentResponse(BaseModel):
    """Response for POST /consent."""

    session_id: str
    status: ConsentStatus
    can_call_outbound: bool
    message: str


# ---------------------------------------------------------------------------
# Gate (in-memory, single-worker)
# ---------------------------------------------------------------------------

class ConsentGate:
    """
    In-memory consent store.

    One ConsentGate instance lives for the lifetime of the server process.
    Sessions are keyed by session_id (a UUID generated by the client).
    No personal data is stored – only the session_id and consent status.
    """

    def __init__(self) -> None:
        self._store: dict[str, ConsentState] = {}

    def get(self, session_id: str) -> ConsentState:
        """Return the current consent state, creating a PENDING entry if new."""
        if session_id not in self._store:
            self._store[session_id] = ConsentState(session_id=session_id)
        return self._store[session_id]

    def grant(self, session_id: str) -> ConsentState:
        """
        Driver tapped Approve. Marks consent as GRANTED.

        Safety invariant: if consent was previously DENIED for this session,
        grant() silently returns the DENIED state unchanged.
        Denied consent is terminal for a session; a new session_id is required.
        """
        existing = self._store.get(session_id)
        if existing and existing.status == ConsentStatus.DENIED:
            # Denied is terminal – do not re-grant
            return existing
        state = ConsentState(
            session_id=session_id,
            status=ConsentStatus.GRANTED,
            timestamp=time.time(),
        )
        self._store[session_id] = state
        return state

    def deny(self, session_id: str) -> ConsentState:
        """Driver tapped Deny. Permanently blocks outbound calls this session."""
        state = ConsentState(
            session_id=session_id,
            status=ConsentStatus.DENIED,
            timestamp=time.time(),
        )
        self._store[session_id] = state
        return state

    def can_call_outbound(self, session_id: str) -> bool:
        """
        Safety check: returns True only if consent is explicitly GRANTED.
        PENDING and DENIED both return False.
        """
        return self.get(session_id).can_call_outbound

    def revoke(self, session_id: str) -> None:
        """Reset consent to PENDING (used by 'delete my data' action)."""
        if session_id in self._store:
            del self._store[session_id]


# Module-level singleton used by main.py
consent_gate = ConsentGate()
